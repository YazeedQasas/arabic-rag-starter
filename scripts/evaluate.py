"""Compare retrieval configurations on the bundled queries.

    python scripts/evaluate.py             # print the tables and write results.md
    python scripts/evaluate.py --depth 5   # judge each query on its top 5 only

Needs the package installed (pip install -e .) or PYTHONPATH=src.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from arabic_rag.data import load_corpus, load_queries
from arabic_rag.evaluation import (
    DEFAULT_DEPTH,
    KS,
    QueryResult,
    Scores,
    ablation_configs,
    run,
    score,
    score_by_kind,
    standard_configs,
)
from arabic_rag.pipeline import HybridRetriever

ROOT = Path(__file__).resolve().parents[1]


def format_table(headers: list[str], rows: list[list[str]]) -> str:
    """An aligned markdown table: first column left-aligned, the rest right-aligned."""
    widths = [max(len(h), *(len(r[i]) for r in rows)) for i, h in enumerate(headers)]

    def line(cells: list[str]) -> str:
        padded = [c.ljust(widths[0]) if i == 0 else c.rjust(widths[i]) for i, c in enumerate(cells)]
        return "| " + " | ".join(padded) + " |"

    rule = "|" + "|".join(
        ("-" * (w + 2) if i == 0 else "-" * (w + 1) + ":") for i, w in enumerate(widths)
    ) + "|"
    return "\n".join([line(headers), rule, *(line(r) for r in rows)])


def metric_headers() -> list[str]:
    return [*(f"recall@{k}" for k in KS), "MRR"]


def metric_cells(s: Scores) -> list[str]:
    return [*(f"{s.recall[k]:.2f}" for k in KS), f"{s.mrr:.2f}"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--depth", type=int, default=DEFAULT_DEPTH, help="results judged per query")
    parser.add_argument("--out", type=Path, default=ROOT / "results.md", help="where to write the report")
    args = parser.parse_args()

    docs, queries = load_corpus(), load_queries()

    def evaluate(configs):
        return {
            name: run(HybridRetriever(docs, cfg), queries, args.depth)
            for name, cfg in configs.items()
        }

    main_results = evaluate(standard_configs())
    # (title, label of the unablated row, its results, the one-rule-off results)
    ablations = [
        ("hybrid", "Hybrid, all rules", main_results["Hybrid, normalized"],
         evaluate(ablation_configs("Hybrid"))),
        ("BM25 alone", "BM25, all rules", main_results["BM25, normalized"],
         evaluate(ablation_configs("BM25", use_ngram=False))),
    ]

    out: list[str] = []
    emit = out.append

    emit("# Evaluation results")
    emit("")
    emit(
        f"{len(docs)} passages, {len(queries)} queries, each judged on its top {args.depth} "
        f"results. Generated by `scripts/evaluate.py`; do not edit by hand."
    )

    # 1. Headline comparison ---------------------------------------------------
    emit("\n## Retrieval configurations\n")
    emit(format_table(
        ["configuration", *metric_headers()],
        [[name, *metric_cells(score(r))] for name, r in main_results.items()],
    ))
    emit("\n`raw` = no normalization; `normalized` = default rules; `Hybrid` = BM25 + n-gram fused with RRF.")

    # 2. By query kind ---------------------------------------------------------
    emit("\n## MRR by query kind\n")
    by_kind = {name: score_by_kind(r) for name, r in main_results.items()}
    kinds = list(next(iter(by_kind.values())))
    counts = {k: s.n for k, s in next(iter(by_kind.values())).items()}
    emit(format_table(
        ["kind", "n", *by_kind],
        [[kind, str(counts[kind]), *(f"{by_kind[name][kind].mrr:.2f}" for name in by_kind)]
         for kind in kinds],
    ))

    # 3. Ablation --------------------------------------------------------------
    for title, full_label, full_results, rule_results in ablations:
        full = score(full_results)
        emit(f"\n## Ablation: {title}, one normalization rule switched off\n")
        rows = [[full_label, *metric_cells(full), "-"]]
        for name, r in rule_results.items():
            s = score(r)
            delta = s.mrr - full.mrr
            rows.append([name, *metric_cells(s), "0.00" if abs(delta) < 0.005 else f"{delta:+.2f}"])
        emit(format_table(["configuration", *metric_headers(), "MRR change"], rows))
    emit(
        "\nA negative change means that rule was helping. Compare the two tables: in the "
        "hybrid, the n-gram ranker often rescues a query that normalization would have "
        "fixed for BM25, so a rule can show 0.00 there while clearly mattering for BM25 "
        "alone. The hybrid degrades without any error, which hides the problem. Rules at "
        "0.00 in both tables contribute nothing on this data (they may still matter on "
        "real text)."
    )

    # 4. Silent failures -------------------------------------------------------
    worst_name = min(main_results, key=lambda n: score(main_results[n]).mrr)
    failures: list[QueryResult] = [r for r in main_results[worst_name] if not r.found]
    emit(f"\n## Silent failures of the worst configuration ({worst_name})\n")
    emit(
        f"{len(failures)} of {len(queries)} queries returned no relevant passage in the top "
        f"{args.depth}, and none of them raised an error:\n"
    )
    for r in failures:
        emit(f"- [{r.query.kind}] {r.query.text}")

    report = "\n".join(out) + "\n"
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to cp1252
    print(report)
    args.out.write_text(report, encoding="utf-8")
    print(f"(written to {args.out})")


if __name__ == "__main__":
    main()
